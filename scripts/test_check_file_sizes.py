import io
import tempfile
import unittest
from contextlib import redirect_stdout
from pathlib import Path
from unittest.mock import patch

import check_file_sizes


class ShouldCheckTests(unittest.TestCase):
    def setUp(self) -> None:
        self.temporary_directory = tempfile.TemporaryDirectory()
        self.root = Path(self.temporary_directory.name) / "vendor" / "checkout"
        self.root.mkdir(parents=True)
        self.root_patch = patch.object(check_file_sizes, "ROOT", self.root)
        self.root_patch.start()

    def tearDown(self) -> None:
        self.root_patch.stop()
        self.temporary_directory.cleanup()

    def write_source(self, relative: str, content: str = "package sample\n") -> Path:
        path = self.root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
        return path

    def test_checkout_ancestor_named_vendor_does_not_hide_source(self) -> None:
        path = self.write_source("cmd/main.go")
        self.assertTrue(check_file_sizes.should_check(path))

    def test_handwritten_source_under_nested_coverage_is_checked(self) -> None:
        path = self.write_source("internal/coverage/report.go")
        self.assertTrue(check_file_sizes.should_check(path))

    def test_generated_directory_exclusion_is_root_relative(self) -> None:
        root_generated = self.write_source("dist/bundle.js")
        nested_source = self.write_source("internal/dist/handwritten.js")
        self.assertFalse(check_file_sizes.should_check(root_generated))
        self.assertTrue(check_file_sizes.should_check(nested_source))

    def test_symlink_is_not_counted_as_source(self) -> None:
        target = self.write_source("internal/target.go")
        link = target.with_name("linked.go")
        link.symlink_to(target)
        self.assertFalse(check_file_sizes.should_check(link))

    def test_generated_header_is_exempt(self) -> None:
        path = self.write_source("generated.go", "/* Generated by tool.\n * DO NOT EDIT.\n */\npackage sample\n")
        self.assertFalse(check_file_sizes.should_check(path))

    def test_css_selector_is_not_a_generated_header(self) -> None:
        path = self.write_source("manual.css", '#generated::before { content: "do not edit"; }\n')
        self.assertTrue(check_file_sizes.should_check(path))

    def test_oversized_css_selector_is_reported_as_failure(self) -> None:
        path = self.write_source(
            "manual.css",
            '#generated::before { content: "do not edit"; }\n' + "a { color: red; }\n" * 1000,
        )
        output = io.StringIO()
        with patch.object(check_file_sizes, "git_paths", return_value=[path]), redirect_stdout(output):
            self.assertEqual(check_file_sizes.main(), 1)
        self.assertIn("FAIL manual.css: 1001 lines", output.getvalue())

    def test_unstarred_multiline_go_generated_header_is_exempt(self) -> None:
        path = self.write_source("generated.go", "/*\nGenerated by tool. DO NOT EDIT.\n*/\npackage sample\n")
        self.assertFalse(check_file_sizes.should_check(path))

    def test_generated_phrase_in_source_code_is_not_a_header(self) -> None:
        path = self.write_source('manual.go', 'var note = "generated; do not edit"\n')
        self.assertTrue(check_file_sizes.should_check(path))

    def test_code_after_block_comment_cannot_complete_generated_header(self) -> None:
        path = self.write_source(
            "manual.go",
            '/* ordinary comment */ var note = "generated; do not edit"\n',
        )
        self.assertTrue(check_file_sizes.should_check(path))

    def test_code_after_html_comment_cannot_complete_generated_header(self) -> None:
        path = self.write_source(
            "manual.html",
            '<!-- ordinary comment --> <script>const note = "generated; do not edit";</script>\n',
        )
        self.assertTrue(check_file_sizes.should_check(path))

    def test_unclosed_comment_cannot_exempt_a_file(self) -> None:
        path = self.write_source("manual.go", "/* generated by tool. do not edit\npackage sample\n")
        self.assertTrue(check_file_sizes.should_check(path))


if __name__ == "__main__":
    unittest.main()
